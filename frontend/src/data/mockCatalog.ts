export function getProductBySlug(slug: string): JewelryProduct | undefined {
  return MOCK_CATALOG.find((p) => p.slug === slug);
}

export function getProductsByCategory(category: string): JewelryProduct[] {
  if (category === 'all') return MOCK_CATALOG;
  return MOCK_CATALOG.filter((p) => p.category.toLowerCase() === category.slice(0, 2).toUpperCase() ||
    p.tags.some((t) => t === category));
}
